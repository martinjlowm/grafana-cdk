import {
  DashboardCursorSync,
  type Dashboard as GrafanaDashboard,
  type DashboardLink as IDashboardLink,
  type TimePickerConfig,
  type VariableModel,
} from '@grafana/schema';
import { Construct } from 'constructs';

import { AnnotationQuery } from '#@/annotation-query.js';
import { DashboardLink } from '#@/dashboard-link.js';
import { GrafanaDataSource } from '#@/data-sources/grafana.js';
import type { DurationString } from '#@/duration.js';
import { GridLayout, type GridPosition } from '#@/grid-position.js';
import type { AnyPanel } from '#@/panel.js';
import { RowPanel } from '#@/row-panel.js';
import { TimeRange, type TimeRangeProps } from '#@/time-range.js';
import type { Variable } from '#@/variables.js';

/**
 * Schema version this package emits. Grafana migrates older dashboards on
 * import; emitting the version whose shape the constructs actually produce is
 * what stops it migrating fields that were already current.
 */
export const SCHEMA_VERSION = 39;

export interface DashboardProps {
  title: string;
  /** Stable identifier, 8–40 characters. Generated by Grafana when omitted. */
  uid?: string;
  description?: string;
  /** Allow edits in the UI. Provisioned dashboards are usually left editable. */
  editable?: boolean;
  /** `0` = January. */
  fiscalYearStartMonth?: number;
  /** Crosshair/tooltip sharing across panels. */
  graphTooltip?: DashboardCursorSync;
  links?: Array<DashboardLink | IDashboardLink>;
  /** Auto-refresh interval; omit for no auto-refresh. */
  refresh?: DurationString;
  tags?: string[];
  /** Default time range. Defaults to Grafana's own `now-6h` → `now`. */
  time?: TimeRangeProps;
  /** Time picker configuration. */
  timepicker?: TimePickerConfig;
  /** IANA zone id, `browser`, or `utc`. */
  timezone?: string;
  /** Lowercase day name, e.g. `monday`. Empty string follows the browser. */
  weekStart?: string;
  /** Redraw at viewport width rather than at the refresh interval. */
  liveNow?: boolean;
  /** Load every panel up front rather than as they scroll into view. */
  preload?: boolean;
  version?: number;
}

/** The dashboard as it appears in the JSON model. */
export type IDashboard = GrafanaDashboard;

/**
 * A Grafana dashboard.
 *
 * Owns the two things a panel cannot know on its own: the grid layout (panels
 * that did not pin `x`/`y` are flowed in the order they were added) and panel
 * ids (unique within the dashboard, assigned in the same order). Both are
 * resolved lazily on the first {@link toJSON}, so panels may be added in any
 * order relative to construction.
 */
export class Dashboard extends Construct {
  public readonly title: string;
  public readonly uid?: string;
  public readonly description?: string;
  public readonly editable: boolean;
  public readonly fiscalYearStartMonth: number;
  public readonly graphTooltip: DashboardCursorSync;
  public readonly links: Array<DashboardLink | IDashboardLink>;
  public readonly refresh?: DurationString;
  public readonly schemaVersion = SCHEMA_VERSION;
  public readonly tags: string[];
  public readonly time: TimeRange;
  public readonly timepicker: TimePickerConfig;
  public readonly timezone: string;
  public readonly weekStart: string;
  public readonly liveNow?: boolean;
  public readonly preload?: boolean;
  public readonly version: number;

  public readonly annotations: AnnotationQuery[];
  public readonly panels: Array<AnyPanel | RowPanel>;
  public readonly variables: Variable[];

  #laidOut = false;

  constructor(scope: Construct, id: string, props: DashboardProps) {
    super(scope, id);

    if (props.uid !== undefined && (props.uid.length < 8 || props.uid.length > 40)) {
      throw new RangeError(
        `Dashboard uid ${JSON.stringify(props.uid)} is ${props.uid.length} characters; Grafana requires 8–40.`,
      );
    }

    if (
      props.fiscalYearStartMonth !== undefined &&
      (props.fiscalYearStartMonth < 0 || props.fiscalYearStartMonth > 11)
    ) {
      throw new RangeError(`fiscalYearStartMonth must be 0–11 (0 = January), got ${props.fiscalYearStartMonth}.`);
    }

    this.title = props.title;
    this.uid = props.uid;
    this.description = props.description;
    this.editable = props.editable ?? true;
    this.fiscalYearStartMonth = props.fiscalYearStartMonth ?? 0;
    this.graphTooltip = props.graphTooltip ?? DashboardCursorSync.Off;
    this.links = props.links ?? [];
    this.refresh = props.refresh;
    this.tags = props.tags ?? [];
    this.time = props.time ? TimeRange.of(props.time) : TimeRange.DEFAULT;
    this.timepicker = props.timepicker ?? {};
    this.timezone = props.timezone ?? 'browser';
    this.weekStart = props.weekStart ?? '';
    this.liveNow = props.liveNow;
    this.preload = props.preload;
    this.version = props.version ?? 0;

    this.panels = [];
    this.variables = [];
    this.annotations = [
      new AnnotationQuery(this, 'annotations-alerts', {
        builtIn: 1,
        datasource: new GrafanaDataSource(this),
        name: 'Annotations & Alerts',
        type: 'dashboard',
      }),
    ];

    this.node.addValidation({ validate: () => this.validate() });
  }

  /** Adds a panel or a row header, in reading order. */
  public addPanel(panel: AnyPanel | RowPanel): void {
    this.panels.push(panel);
    this.#laidOut = false;
  }

  /** Adds a template variable. */
  public addVariable(variable: Variable): void {
    this.variables.push(variable);
  }

  /** Adds an annotation query alongside the built-in one. */
  public addAnnotation(annotation: AnnotationQuery): void {
    this.annotations.push(annotation);
  }

  /**
   * Resolves flowed grid positions and unassigned panel ids.
   *
   * Idempotent, and run automatically by {@link toJSON} and by validation, so
   * callers never have to. Rows reset the layout cursor: panels under a row
   * start a fresh line rather than continuing the previous row's.
   */
  public layout(): void {
    if (this.#laidOut) {
      return;
    }

    const grid = new GridLayout();
    let nextId = 1 + Math.max(0, ...this.allPanels().map((panel) => panel.id ?? 0));

    // Rows and panels share one cursor: a row is 24 columns wide, so placing it
    // through the same layout is what makes the panels after it start a fresh
    // line instead of continuing the previous one.
    for (const panel of this.panels) {
      grid.place(panel.gridPos);
    }

    for (const panel of this.allPanels()) {
      if (panel.id === undefined) {
        panel.assignId(nextId++);
      }
    }

    this.#laidOut = true;
  }

  /** Every panel in the dashboard, including those nested in collapsed rows. */
  private allPanels(): Array<AnyPanel | RowPanel> {
    return this.panels.flatMap((panel) => (panel instanceof RowPanel ? [panel, ...panel.panels] : [panel]));
  }

  private validate(): string[] {
    this.layout();

    const errors: string[] = [];

    const positions: Array<{ path: string; position: GridPosition }> = this.panels.map((panel) => ({
      path: panel.node.path,
      position: panel.gridPos,
    }));
    errors.push(...GridLayout.validateNoOverlap(positions));

    const ids = new Map<number, string>();
    for (const panel of this.allPanels()) {
      if (panel.id === undefined) {
        continue;
      }

      const existing = ids.get(panel.id);
      if (existing) {
        errors.push(`duplicate panel id ${panel.id} on [${existing}] and [${panel.node.path}]`);
      }
      ids.set(panel.id, panel.node.path);
    }

    const variableNames = new Set<string>();
    for (const variable of this.variables) {
      if (variableNames.has(variable.name)) {
        errors.push(`duplicate template variable '${variable.name}': '$${variable.name}' would be ambiguous`);
      }
      variableNames.add(variable.name);
    }

    return errors;
  }

  public toJSON(): IDashboard {
    this.layout();

    const templating: VariableModel[] = this.variables.map((variable) => variable.toJSON());

    return {
      annotations: { list: this.annotations.map((annotation) => annotation.toJSON()) },
      ...(this.description === undefined ? {} : { description: this.description }),
      editable: this.editable,
      fiscalYearStartMonth: this.fiscalYearStartMonth,
      graphTooltip: this.graphTooltip,
      id: null,
      links: this.links.map((link) => (link instanceof DashboardLink ? link.toJSON() : link)),
      ...(this.liveNow === undefined ? {} : { liveNow: this.liveNow }),
      panels: this.panels.map((panel) => panel.toJSON()),
      ...(this.preload === undefined ? {} : { preload: this.preload }),
      ...(this.refresh === undefined ? {} : { refresh: this.refresh }),
      schemaVersion: this.schemaVersion,
      tags: this.tags,
      templating: { list: templating },
      time: this.time.toJSON(),
      timepicker: this.timepicker,
      timezone: this.timezone,
      title: this.title,
      ...(this.uid === undefined ? {} : { uid: this.uid }),
      version: this.version,
      weekStart: this.weekStart,
    } as IDashboard;
  }

  /** The dashboard model as the JSON text Grafana imports. */
  public toJSONString(space: string | number = 2): string {
    return JSON.stringify(this.toJSON(), null, space);
  }
}
